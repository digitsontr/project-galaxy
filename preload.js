  load: () => ipcRenderer.invoke('galaxy:load'),
  save: (project) => ipcRenderer.invoke('galaxy:save', project),
  openFolder: (p) => ipcRenderer.invoke('galaxy:openFolder', p),
  openClaude: (p) => ipcRenderer.invoke('galaxy:openClaude', p),
  tree: (p) => ipcRenderer.invoke('galaxy:tree', p),
